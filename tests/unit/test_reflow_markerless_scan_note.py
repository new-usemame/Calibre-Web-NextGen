class Probe:
    def __init__(self,ink=INK):self.ink=ink
    def source_ink_bounds(self,box):
        b=self.ink
        if b and box[0]<=b[0] and box[1]<=b[1] and box[2]>=b[2] and box[3]>=b[3]:return b
        return None
    ink_bounds=source_ink_bounds

def witness(boundary=None):
    d=deepcopy(SOURCE)
    if boundary=='caption':d['l86']['spans'][0]['text']='Plate 7 '
    if boundary=='attached':
        for key in ('l86','l87'):
            row=d[key];row['bbox'][1]-=10;row['bbox'][3]-=10
            for sp in row['spans']:sp['bbox'][1]-=10;sp['bbox'][3]-=10;sp['origin_y']-=10
    if boundary=='body_type':
        for key in ('l86','l87'):
            for sp in d[key]['spans']:sp['size']=11;sp['bbox'][3]=sp['bbox'][1]+7.92
    def line(key):
        r=d[key];return extract.Line([extract.Span(**dict(s,bbox=tuple(s['bbox']))) for s in r['spans']],tuple(r['bbox']))
    body=[line('l84'),line('l85')];notes=[line('l86'),line('l87')]
    def block(n,ls):return extract.Block(n,(min(l.bbox[0] for l in ls),min(l.bbox[1] for l in ls),max(l.bbox[2] for l in ls),max(l.bbox[3] for l in ls)),ls)
    raw=extract.RawPage(26,841.68,595.2,[block(10,body),block(11,notes)],images=[extract.Image((0,0,841.68,595.2),1)],source_geometry={'space':'reading','orientation':90});raw.text_layer_invisible=True
    return raw,notes

def test_source_pixel_marker_missing_from_ocr_proves_an_unnumbered_note():
    raw,rows=witness();before=asdict(raw)
    body,notes=skeleton._split_off_notes(raw,skeleton.BookStyle(body_size=11),skeleton.PageSkeleton(26,841.68,595.2),Probe())
    assert len(notes)==1,'Detached right bibliography must leave the running sentence'
    assert notes[0].number is None and notes[0].uncertain
    assert notes[0].lines==rows and notes[0].text.startswith('Artisan')
    assert not any(row in b.lines for row in rows for b in body)
    assert asdict(raw)==before
    assert sum(len(l.spans) for b in body for l in b.lines)+sum(len(l.spans) for n in notes for l in n.lines)==sum(len(l.spans) for b in raw.blocks for l in b.lines)

@pytest.mark.parametrize('ink',[None,(452.85,543.2,454.85,549.0),(450,539.67,460,542.33),(420,539.67,422,542.33)])
def test_absent_baseline_large_or_other_column_ink_is_not_a_note(ink):
    raw,rows=witness()
    body,notes=skeleton._split_off_notes(raw,skeleton.BookStyle(body_size=11),skeleton.PageSkeleton(26,841.68,595.2),Probe(ink))
    assert not notes
    assert all(any(row in b.lines for b in body) for row in rows)

